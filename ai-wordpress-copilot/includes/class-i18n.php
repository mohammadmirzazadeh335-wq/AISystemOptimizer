	/**
	 * Strings for one language.
	 *
	 * @param string $lang 'fa' or 'en'.
	 * @return array
	 */
	public static function for_language( $lang ) {
		$all = self::strings();
		return isset( $all[ $lang ] ) ? $all[ $lang ] : $all['fa'];
	}

	/**
	 * Current UI language from settings.
	 *
	 * @return string
	 */
	public static function current_language() {
		$lang = Settings::get( 'ui_language', 'fa' );
		return in_array( $lang, array( 'fa', 'en' ), true ) ? $lang : 'fa';
	}
